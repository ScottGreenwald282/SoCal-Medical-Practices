def norm_name(value: str) -> str:
    value = value.lower().replace(".", " ")
    value = re.sub(r"[^a-z\s]", "", value)
    return re.sub(r"\s+", " ", value).strip()


def norm_domain(value: str) -> str:
    value = value.lower().strip()
    value = re.sub(r"^https?://", "", value)
    value = value.split("/")[0]
    if value.startswith("www."):
        value = value[4:]
    return value


def validate(rows: list[dict]) -> list[str]:
    errors = []
    seen = set()
    for i, row in enumerate(rows, start=1):
        status = row["Qualification Status"]
        if status not in {"QUALIFIED", "REVIEW_REQUIRED", "EXCLUDED"}:
            errors.append(f"row {i} bad status {status}")
        state = row["State"]
        if state in EXCLUDED_STATES and status == "QUALIFIED":
            errors.append(f"row {i} qualified in excluded state {state}")
        if status == "QUALIFIED":
            for field in (
                "First Name",
                "Last Name",
                "Title",
                "Company",
                "State",
                "Person Source URL",
                "Person Evidence",
                "Company Source URL 1",
                "Company Evidence 1",
                "Investor Lending Evidence",
                "Outside Lender/Broker Evidence",
                "Business Model",
            ):
                if not str(row.get(field, "")).strip():
                    errors.append(f"row {i} qualified missing {field}")
            if row["DNC Status"] != "NOT_YET_SCREENED":
                errors.append(f"row {i} DNC status must remain NOT_YET_SCREENED")
            if row["Geography Qualified"] != "YES":
                errors.append(f"row {i} geography not qualified")
        key = (norm_name(row["Full Name"]), norm_domain(row["Company Domain"]))
        if key in seen and status == "QUALIFIED":
            errors.append(f"duplicate qualified key {key}")
        if status == "QUALIFIED":
            seen.add(key)
        if row["Business Email"] and row["Email Status"] != "PUBLIC":
            errors.append(f"row {i} email without PUBLIC status")
        if "INFERRED" in row["Email Status"]:
            errors.append(f"row {i} inferred email stored as status improperly")
    return errors


def write_csv(path: Path, columns: list[str], rows: list[dict]) -> None:
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=columns, extrasaction="ignore")
        writer.writeheader()
        for row in rows:
            writer.writerow(row)


